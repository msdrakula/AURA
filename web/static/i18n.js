function detectLang() {
  try {
    const s = localStorage.getItem("aura_lang") || localStorage.getItem("meb_lang");
    if (s === "ru" || s === "en") return s;
  } catch (_) {}
  return "en";
}

function tr(key, vars) {
  const dict = I18N[mebLang] || I18N.en;
  let s = dict[key];
  if (s == null) s = I18N.en[key];
  if (s == null) s = key;
  if (vars) Object.keys(vars).forEach((k) => { s = s.split("{" + k + "}").join(String(vars[k])); });
  return s;
}

function setLang(name) {
  mebLang = name === "ru" ? "ru" : "en";
  document.documentElement.lang = mebLang;
  document.documentElement.setAttribute("data-lang", mebLang);
  try { localStorage.setItem("aura_lang", mebLang); } catch (_) {}
}

function applyI18nDom() {
  document.title = tr("doc.title");
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    if (el.id === "mapDetail") return;
    const dot = el.querySelector(":scope > .dot");
    el.textContent = tr(el.getAttribute("data-i18n"));
    if (dot) el.appendChild(dot);
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = tr(el.getAttribute("data-i18n-html"));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = tr(el.getAttribute("data-i18n-placeholder"));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = tr(el.getAttribute("data-i18n-title"));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", tr(el.getAttribute("data-i18n-aria")));
  });
  applyNavLabels();
}

const NAV_I18N = {
  map: "nav.map",
  proxy: "nav.proxy",
  discover: "nav.discover",
  fuzz: "nav.fuzz",
  intruder: "nav.intruder",
  repeater: "nav.repeater",
  scope: "nav.scope",
  scanner: "nav.scanner",
  logger: "nav.logger",
  decoder: "nav.decoder",
  comparer: "nav.comparer",
  sequencer: "nav.sequencer",
  collaborator: "nav.collaborator",
  organizer: "nav.organizer",
  other: "nav.other",
  extensions: "nav.extensions",
};

function applyNavLabels() {
  document.querySelectorAll("#mainTabs button[data-view]").forEach((b) => {
    const key = NAV_I18N[b.dataset.view];
    if (!key) return;
    const label = tr(key);
    const labeled = b.querySelector("[data-i18n]");
    const dot = b.querySelector(".dot");
    if (labeled && labeled !== b) {
      labeled.textContent = label;
      return;
    }
    b.textContent = label;
    if (dot) b.appendChild(dot);
  });
}

mebLang = detectLang();
